  static Future<void> _cachePreviews(List<String> paths) async {
    for (final previewPath in paths) {
      try {
        final bytes = await readEncryptedBytes(previewPath);
        UniversalImageCache.instance.put(previewPath, previewPath, bytes);
      } catch (e) {
        // The database update is already durable. A cache miss is safe because
        // UniversalImage will load the preview from disk when it is displayed.
        AppLogger.error('Failed to cache repaired preview $previewPath', e);
      }
    }
  }

  static Future<void> _deleteGeneratedPreviews(List<String> paths) async {
    if (paths.isEmpty) return;
    final fs = await fileSystem();
    for (final previewPath in paths) {
      UniversalImageCache.instance.invalidate(previewPath);
      if (await fs.exists(previewPath)) await fs.delete(previewPath);
    }
  }
