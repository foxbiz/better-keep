enum SketchPreviewRepairStatus {
  notNeeded,
  repaired,
  retryableFailure,
  deferredLocked,
  resolvedWithPlaceholder,
}

enum SketchPreviewRepairScope { allSketches, imageSketchesOnly }

@immutable
class SketchPreviewRepairResult {
  final SketchPreviewRepairStatus status;
  final bool changed;
  final String sourceSignature;
  final Set<String> completedSketchKeys;
  final Set<String> failedSketchKeys;

  const SketchPreviewRepairResult({
    required this.status,
    required this.sourceSignature,
    this.changed = false,
    this.completedSketchKeys = const {},
    this.failedSketchKeys = const {},
  });

  bool get isComplete => status != SketchPreviewRepairStatus.retryableFailure;
}

@immutable
class SketchPreviewRepairBatchResult {
  final bool changed;
  final bool hasRetryableFailure;
  final Set<String> completedSketchKeys;
  final Set<String> failedSketchKeys;
  final Set<String> discardedPreviewPaths;

  const SketchPreviewRepairBatchResult({
    this.changed = false,
    this.hasRetryableFailure = false,
    this.completedSketchKeys = const {},
    this.failedSketchKeys = const {},
    this.discardedPreviewPaths = const {},
  });
}

enum SketchPreviewLocalProgressState {
  complete,
  pending,
  resolvedWithPlaceholder,
}

@immutable
class SketchPreviewLocalProgress {
  final String sourceSignature;
  final SketchPreviewLocalProgressState state;
  final int failedAttempts;
  final Set<String> completedSketchKeys;

  const SketchPreviewLocalProgress({
    required this.sourceSignature,
    required this.state,
    this.failedAttempts = 0,
    this.completedSketchKeys = const {},
  });

  factory SketchPreviewLocalProgress.fromJson(Map<String, dynamic> json) {
    final stateName = json['state'] as String?;
    return SketchPreviewLocalProgress(
      sourceSignature: json['sourceSignature'] as String? ?? '',
      state: SketchPreviewLocalProgressState.values.firstWhere(
        (value) => value.name == stateName,
        orElse: () => SketchPreviewLocalProgressState.pending,
      ),
      failedAttempts: json['failedAttempts'] as int? ?? 0,
      completedSketchKeys: Set<String>.from(
        (json['completedSketchKeys'] as List<dynamic>? ?? const [])
            .whereType<String>(),
      ),
    );
  }

  Map<String, dynamic> toJson() => {
    'sourceSignature': sourceSignature,
    'state': state.name,
    'failedAttempts': failedAttempts,
    'completedSketchKeys': completedSketchKeys.toList()..sort(),
  };
}

/// Performs a local-only, idempotent repair of previews generated by the old
/// fixed-canvas sync renderer. No repair metadata is written to note JSON.
class SketchPreviewRepairService {
  SketchPreviewRepairService._();

  static String get _preferenceKey =>
      FirebaseScopedPreferences.key('sketch_preview_renderer_version');
  // Version 4 regenerates previews which may have been distorted when editor
  // saves independently clamped both axes of an oversized image canvas.
  static const _currentVersion = 4;
  static String get _progressPreferenceKey => FirebaseScopedPreferences.key(
    'sketch_preview_renderer_v4_repair_progress',
  );
  static const _maxAutomaticFailures = 3;
  static String get _unlockedRepairPreferenceKey =>
      FirebaseScopedPreferences.key(
        'sketch_preview_renderer_v2_unlocked_note_ids',
      );
  static bool _running = false;
  static final Set<int> _startupAttemptedNoteIds = {};

  @visibleForTesting
  static Future<bool> Function(SketchData sketch)? previewGeneratorOverride;

  @visibleForTesting
  static int get currentVersion => _currentVersion;

  static Future<void> runIfNeeded() async {
    if (_running) return;
    final prefs = await AppState.prefs;
    if ((prefs.getInt(_preferenceKey) ?? 0) >= _currentVersion) return;

    _running = true;
    try {
      // Keep only stable identifiers. Each row is loaded immediately before
      // rendering so startup never retains stale full-note snapshots.
      final candidates = await AppState.db.query('note', columns: ['id']);
      final progress = _loadProgress(prefs);
      final activeIds = <int>{};
      var allComplete = true;

      for (final candidate in candidates) {
        final id = candidate['id'] as int?;
        if (id == null) continue;
        activeIds.add(id);

        final previous = progress[id];
        if (_startupAttemptedNoteIds.contains(id)) {
          if (previous?.state == SketchPreviewLocalProgressState.pending) {
            allComplete = false;
          }
          continue;
        }
        _startupAttemptedNoteIds.add(id);

        SketchPreviewRepairResult result;
        try {
          result = await repairNoteById(
            id,
            scope: SketchPreviewRepairScope.imageSketchesOnly,
            expectedSourceSignature: previous?.sourceSignature,
            completedSketchKeys: previous?.completedSketchKeys ?? const {},
            suppressMatchingSource:
                previous?.state ==
                SketchPreviewLocalProgressState.resolvedWithPlaceholder,
          );
        } catch (e, stackTrace) {
          AppLogger.error(
            'Unexpected startup preview repair failure for note $id',
            e,
            stackTrace,
          );
          result = SketchPreviewRepairResult(
            status: SketchPreviewRepairStatus.retryableFailure,
            sourceSignature: previous?.sourceSignature ?? '',
            completedSketchKeys: previous?.completedSketchKeys ?? const {},
          );
        }

        final next = advanceLocalProgress(previous: previous, result: result);
        progress[id] = next;
        await _saveProgress(prefs, progress);
        if (result.status == SketchPreviewRepairStatus.retryableFailure) {
          final failedSketches = result.failedSketchKeys.isEmpty
              ? 'unknown or concurrent update'
              : result.failedSketchKeys.join(',');
          AppLogger.log(
            'Preview repair attempt ${next.failedAttempts} failed for note $id '
            '(sketches: $failedSketches)',
          );
        }
        if (next.state ==
                SketchPreviewLocalProgressState.resolvedWithPlaceholder &&
            previous?.state !=
                SketchPreviewLocalProgressState.resolvedWithPlaceholder) {
          AppLogger.log(
            'Using placeholder after ${next.failedAttempts} failed preview '
            'repair attempts for note $id',
          );
        }
        if (next.state == SketchPreviewLocalProgressState.pending) {
          allComplete = false;
        }
      }

      progress.removeWhere((id, _) => !activeIds.contains(id));
      await _saveProgress(prefs, progress);

      if (allComplete) {
        await prefs.setInt(_preferenceKey, _currentVersion);
      } else {
        AppLogger.log(
          'Sketch preview repair deferred; failed notes will retry next launch',
        );
      }
    } catch (e, stackTrace) {
      AppLogger.error('Sketch preview repair failed', e, stackTrace);
    } finally {
      _running = false;
    }
  }

  /// Coordinates a version marker for callers which perform one atomic repair
  /// operation. The startup scan uses per-note progress, while this helper
  /// keeps the marker-after-success contract independently testable.
  @visibleForTesting
  static Future<bool> runVersionedRepair({
    required int storedVersion,
    required Future<void> Function() repair,
    required Future<void> Function(int version) markComplete,
  }) async {
    if (storedVersion >= _currentVersion) return false;
    await repair();
    await markComplete(_currentVersion);
    return true;
  }

  @visibleForTesting
  static SketchPreviewLocalProgress advanceLocalProgress({
    required SketchPreviewLocalProgress? previous,
    required SketchPreviewRepairResult result,
    int maxAutomaticFailures = _maxAutomaticFailures,
  }) {
    final sameSource =
        previous != null && previous.sourceSignature == result.sourceSignature;

    if (result.status == SketchPreviewRepairStatus.retryableFailure) {
      final failedAttempts = sameSource ? previous.failedAttempts + 1 : 1;
      final resolved = failedAttempts >= maxAutomaticFailures;
      return SketchPreviewLocalProgress(
        sourceSignature: result.sourceSignature,
        state: resolved
            ? SketchPreviewLocalProgressState.resolvedWithPlaceholder
            : SketchPreviewLocalProgressState.pending,
        failedAttempts: failedAttempts,
        completedSketchKeys: result.completedSketchKeys,
      );
    }

    if (result.status == SketchPreviewRepairStatus.resolvedWithPlaceholder) {
      return SketchPreviewLocalProgress(
        sourceSignature: result.sourceSignature,
        state: SketchPreviewLocalProgressState.resolvedWithPlaceholder,
        failedAttempts: sameSource ? previous.failedAttempts : 0,
        completedSketchKeys: result.completedSketchKeys,
      );
    }

    return SketchPreviewLocalProgress(
      sourceSignature: result.sourceSignature,
      state: SketchPreviewLocalProgressState.complete,
      completedSketchKeys: result.completedSketchKeys,
    );
  }

  static Future<SketchPreviewRepairBatchResult> repairNote(
    Note note, {
    SketchPreviewRepairScope scope = SketchPreviewRepairScope.allSketches,
    bool reuseExistingPreviews = true,
    bool updateCache = true,
    Set<String> completedSketchKeys = const {},
    Future<bool> Function(String path)? pathExists,
    Future<bool> Function(SketchData sketch)? generatePreview,
  }) async {
    var changed = false;
    var hasRetryableFailure = false;
    final completed = <String>{};
    final failed = <String>{};
    final discardedPreviewPaths = <String>{};
    final fs = await fileSystem();
    final exists = pathExists ?? fs.exists;
    final generate =
        generatePreview ??
        previewGeneratorOverride ??
        (sketch) => SketchPreviewGenerator.generatePreview(
          sketch,
          reuseExistingPreview: reuseExistingPreviews,
          updateCache: updateCache,
        );
    bool clearPresentationForRetry(SketchData sketch) {
      if (sketch.previewImage == null && sketch.blurredThumbnail == null) {
        return false;
      }
      final failedPreview = sketch.previewImage;
      if (failedPreview != null &&
          failedPreview.isNotEmpty &&
          !failedPreview.startsWith('http')) {
        discardedPreviewPaths.add(failedPreview);
      }
      sketch.previewImage = null;
      sketch.blurredThumbnail = null;
      return true;
    }

    for (final (index, sketch) in note.sketches.indexed) {
      final backgroundPath = sketch.backgroundImage;
      final isImageBased = backgroundPath != null && backgroundPath.isNotEmpty;
      if (scope == SketchPreviewRepairScope.imageSketchesOnly &&
          !isImageBased) {
        continue;
      }

      final sketchKey = _sketchSourceKey(index, sketch);
      if (sketch.requiresLegacyMigration) {
        hasRetryableFailure = true;
        failed.add(sketchKey);
        changed = clearPresentationForRetry(sketch) || changed;
        continue;
      }
      if (completedSketchKeys.contains(sketchKey) &&
          await _hasUsableLocalPreview(sketch, exists)) {
        completed.add(sketchKey);
        continue;
      }

      if (isImageBased &&
          (backgroundPath.startsWith('http') ||
              !await exists(backgroundPath))) {
        hasRetryableFailure = true;
        failed.add(sketchKey);
        changed = clearPresentationForRetry(sketch) || changed;
        continue;
      }

      if (!sketch.hasHydratedStrokeSource) {
        final hydration = await SketchStrokesFileService.hydrate(
          sketch,
          pathExists: exists,
        );
        if (hydration == SketchStrokesLoadResult.empty) {
          completed.add(sketchKey);
          continue;
        }
        if (!hydration.hasStrokes) {
          // Missing, invalid, remote, legacy, or still-protected files may
          // become available after sync/unlock and must keep this note pending.
          hasRetryableFailure = true;
          failed.add(sketchKey);
          changed = clearPresentationForRetry(sketch) || changed;
          continue;
        }
      }

      if (sketch.strokes.isEmpty) {
        // An empty drawing is complete only after its source was parsed. This
        // prevents a locked, unhydrated sketch from being mistaken for empty.
        if (sketch.hasHydratedStrokeSource) {
          completed.add(sketchKey);
        } else {
          hasRetryableFailure = true;
          failed.add(sketchKey);
        }
        continue;
      }
      final previousPreview = sketch.previewImage;
      final generated = await generate(sketch);
      if (generated) {
        changed = true;
        if (previousPreview != null &&
            previousPreview.isNotEmpty &&
            !previousPreview.startsWith('http') &&
            previousPreview != sketch.previewImage) {
          discardedPreviewPaths.add(previousPreview);
        }
        if (await _hasUsableLocalPreview(sketch, exists)) {
          completed.add(sketchKey);
          continue;
        }
      }

      hasRetryableFailure = true;
      failed.add(sketchKey);
      // An old fixed-renderer or partially written preview is less useful than
      // the normal unavailable placeholder while a safe retry is pending.
      if (!generated) {
        changed = clearPresentationForRetry(sketch) || changed;
      }
    }

    return SketchPreviewRepairBatchResult(
      changed: changed,
      hasRetryableFailure: hasRetryableFailure,
      completedSketchKeys: completed,
      failedSketchKeys: failed,
      discardedPreviewPaths: discardedPreviewPaths,
    );
  }

  @visibleForTesting
  static Future<SketchPreviewRepairResult> repairNoteById(
    int id, {
    SketchPreviewRepairScope scope = SketchPreviewRepairScope.allSketches,
    bool allowLocked = false,
    String? expectedSourceSignature,
    Set<String> completedSketchKeys = const {},
    bool suppressMatchingSource = false,
    Future<SketchPreviewRepairBatchResult> Function(
      Note note,
      Set<String> completedSketchKeys,
    )?
    repair,
    Future<void> Function(Note repairedNote)? onPersisted,
    Future<void> Function(List<String> paths)? cachePreviews,
    Future<void> Function(List<String> paths)? deleteGeneratedPreviews,
  }) async {
    final repairPreviews =
        repair ??
        (note, completed) => repairNote(
          note,
          scope: scope,
          reuseExistingPreviews: false,
          updateCache: false,
          completedSketchKeys: completed,
        );
    final cache = cachePreviews ?? _cachePreviews;
    final cleanup = deleteGeneratedPreviews ?? _deleteGeneratedPreviews;
    var lastSourceSignature = expectedSourceSignature ?? '';
    var lastCompletedSketchKeys = completedSketchKeys;

    for (var attempt = 0; attempt < 2; attempt++) {
      final rows = await AppState.db.query(
        'note',
        where: 'id = ?',
        whereArgs: [id],
        limit: 1,
      );
      if (rows.isEmpty) {
        return const SketchPreviewRepairResult(
          status: SketchPreviewRepairStatus.notNeeded,
          sourceSignature: '',
        );
      }

      final row = rows.single;
      final note = await Note.fromJsonAsync(row);
      final sourceSignature = sourceSignatureFor(note);
      lastSourceSignature = sourceSignature;
      final sameSource = expectedSourceSignature == sourceSignature;
      final effectiveCompleted = sameSource ? completedSketchKeys : <String>{};
      lastCompletedSketchKeys = effectiveCompleted;

      if (note.locked && !allowLocked) {
        return SketchPreviewRepairResult(
          status: SketchPreviewRepairStatus.deferredLocked,
          sourceSignature: sourceSignature,
          completedSketchKeys: effectiveCompleted,
        );
      }
      if (suppressMatchingSource && sameSource) {
        return SketchPreviewRepairResult(
          status: SketchPreviewRepairStatus.resolvedWithPlaceholder,
          sourceSignature: sourceSignature,
          completedSketchKeys: effectiveCompleted,
        );
      }

      final previousPaths = <Object, String?>{
        for (final sketch in note.sketches) sketch: sketch.previewImage,
      };
      final generatedPaths = <String>[];
      var persisted = false;
      SketchPreviewRepairBatchResult? batch;
      void collectGeneratedPaths() {
        for (final sketch in note.sketches) {
          final generatedPath = sketch.previewImage;
          if (generatedPath != null &&
              generatedPath != previousPaths[sketch] &&
              !generatedPath.startsWith('http') &&
              !generatedPaths.contains(generatedPath)) {
            generatedPaths.add(generatedPath);
          }
        }
      }

      try {
        batch = await repairPreviews(note, effectiveCompleted);
        collectGeneratedPaths();
        lastCompletedSketchKeys = batch.completedSketchKeys;
        if (!batch.changed) {
          await cleanup(generatedPaths);
          return SketchPreviewRepairResult(
            status: batch.hasRetryableFailure
                ? SketchPreviewRepairStatus.retryableFailure
                : SketchPreviewRepairStatus.notNeeded,
            sourceSignature: sourceSignature,
            completedSketchKeys: batch.completedSketchKeys,
            failedSketchKeys: batch.failedSketchKeys,
          );
        }

        final attachments = await note.serializeAttachmentsForLocalStorage();
        persisted = await Note.updateAttachmentsIfUnchanged(
          id: id,
          expectedUpdatedAt: row['updated_at'],
          expectedAttachments: row['attachments'],
          attachments: attachments,
        );
        if (persisted) {
          await cache(generatedPaths);
          await cleanup(batch.discardedPreviewPaths.toList());
          await onPersisted?.call(note);
          return SketchPreviewRepairResult(
            status: batch.hasRetryableFailure
                ? SketchPreviewRepairStatus.retryableFailure
                : SketchPreviewRepairStatus.repaired,
            changed: true,
            sourceSignature: sourceSignature,
            completedSketchKeys: batch.completedSketchKeys,
            failedSketchKeys: batch.failedSketchKeys,
          );
        }
      } catch (e, stackTrace) {
        collectGeneratedPaths();
        if (!persisted) await cleanup(generatedPaths);
        AppLogger.error(
          'Failed to persist repaired sketch preview for note $id',
          e,
          stackTrace,
        );
        if (persisted && batch != null) {
          // The attachment-only update is already durable. Cache population
          // and in-memory copying are optional and can self-heal on next load.
          return SketchPreviewRepairResult(
            status: batch.hasRetryableFailure
                ? SketchPreviewRepairStatus.retryableFailure
                : SketchPreviewRepairStatus.repaired,
            changed: true,
            sourceSignature: sourceSignature,
            completedSketchKeys: batch.completedSketchKeys,
            failedSketchKeys: batch.failedSketchKeys,
          );
        }
        return SketchPreviewRepairResult(
          status: SketchPreviewRepairStatus.retryableFailure,
          sourceSignature: sourceSignature,
          completedSketchKeys: effectiveCompleted,
          failedSketchKeys: batch?.failedSketchKeys ?? const {},
        );
      }

      // The row changed while rendering. The generated files were never made
      // visible through either the database or cache, so discard and retry
      // from the current row once.
      await cleanup(generatedPaths);
    }

    AppLogger.log(
      'Deferred sketch preview repair for actively edited note $id',
    );
    return SketchPreviewRepairResult(
      status: SketchPreviewRepairStatus.retryableFailure,
      sourceSignature: lastSourceSignature,
      completedSketchKeys: lastCompletedSketchKeys,
    );
  }

  /// Repairs a locked note after its password-protected files have been
  /// decrypted by a successful unlock. The generated metadata remains local.
  static Future<bool> repairAfterUnlock(Note unlockedNote) async {
    final noteId = unlockedNote.id;
    if (noteId == null || !unlockedNote.locked || !unlockedNote.unlocked) {
      return false;
    }

    try {
      await SketchStrokesFileService.hydrateDecrypted(
        unlockedNote.sketches,
        hydrateSketch: (sketch) => SketchStrokesFileService.hydrate(
          sketch,
          passwordProtectedDecoder: unlockedNote.decryptAttachmentForSession,
        ),
      );
      SketchPreviewRepairResult? repairResult;
      final repaired = await runFirstUnlockRepair(
        noteId: noteId,
        previewIsComplete: () =>
            hasCompleteLocalAttachmentPreviews(unlockedNote),
        repair: () async {
          repairResult = await repairNoteById(
            noteId,
            allowLocked: true,
            repair: (note, completed) async {
              await overlayVerifiedUnlockedSources(unlockedNote, note);
              return repairDecryptedAttachments(
                note,
                completedSketchKeys: completed,
                readBytes: unlockedNote.readAttachmentForSession,
                writeBytes: unlockedNote.writeAttachmentForSession,
              );
            },
            cachePreviews: (_) async {},
            onPersisted: (repairedNote) async {
              _copyPreviewFields(repairedNote, unlockedNote);
            },
          );
          return repairResult!.isComplete;
        },
      );
      if (repaired && repairResult != null) {
        await _recordForcedRepairOutcome(noteId, repairResult!);
      }
      return repaired;
    } catch (e, stackTrace) {
      AppLogger.error(
        'Failed to repair previews after unlocking note $noteId',
        e,
        stackTrace,
      );
      return false;
    }
  }

  /// Copies a verified in-memory drawing into the fresh guarded database row.
  ///
  /// Current files were authenticated immediately before this call and remain
  /// ENCP-protected at their canonical paths. Both current and freshly
  /// migrated sources use the same strict attachment-index and path match.
  @visibleForTesting
  static Future<void> overlayVerifiedUnlockedSources(
    Note source,
    Note target,
  ) async {
    final count = source.attachments.length < target.attachments.length
        ? source.attachments.length
        : target.attachments.length;
    for (var index = 0; index < count; index++) {
      final sourceAttachment = source.attachments[index];
      final targetAttachment = target.attachments[index];
      if (sourceAttachment.type != AttachmentType.sketch ||
          targetAttachment.type != AttachmentType.sketch) {
        continue;
      }
      final sourceSketch = sourceAttachment.sketch!;
      final targetSketch = targetAttachment.sketch!;
      final sourcePath = sourceSketch.strokesFilePath;
      if (!sourceSketch.hasHydratedStrokeSource ||
          sourceSketch.isLegacyQuarantined ||
          sourceSketch.legacyMigrationState ==
              LegacySketchMigrationState.pending ||
          sourcePath == null ||
          sourcePath.isEmpty ||
          sourcePath != targetSketch.strokesFilePath) {
        continue;
      }
      targetSketch.strokes = List<SketchStroke>.from(sourceSketch.strokes);
      targetSketch.backgroundColor = sourceSketch.backgroundColor;
      targetSketch.pagePattern = sourceSketch.pagePattern;
      targetSketch.aspectRatio = sourceSketch.aspectRatio;
      targetSketch.markStrokesHydrated();

      // A manual retry can resolve a background URL after the fresh database
      // row was loaded. Adopt that local path only when file tracking proves
      // it is the exact same remote source.
      final sourceBackground = sourceSketch.backgroundImage;
      final targetBackground = targetSketch.backgroundImage;
      if (sourceBackground != null &&
          sourceBackground.isNotEmpty &&
          !sourceBackground.startsWith('http') &&
          targetBackground != null &&
          targetBackground.startsWith('http')) {
        final tracking = await FileSyncTrack.getByLocalPath(sourceBackground);
        if (tracking?.remotePath == targetBackground) {
          targetSketch.backgroundImage = sourceBackground;
        }
      }
    }
  }

  /// Repairs missing previews opened from the editor without treating the
  /// repair as a user edit or triggering sync.
  static Future<bool> repairMissingPreviews(Note note) async {
    final noteId = note.id;
    if (noteId == null) return false;

    try {
      final result = await repairNoteById(
        noteId,
        allowLocked: note.locked && note.unlocked,
        onPersisted: (repairedNote) async {
          _copyPreviewFields(repairedNote, note);
        },
      );
      if (result.isComplete) {
        await _recordForcedRepairOutcome(noteId, result);
      }
      return result.isComplete;
    } catch (e, stackTrace) {
      AppLogger.error(
        'Failed to self-heal sketch previews for note $noteId',
        e,
        stackTrace,
      );
      return false;
    }
  }

  @visibleForTesting
  static Future<bool> runFirstUnlockRepair({
    required int noteId,
    required Future<bool> Function() previewIsComplete,
    required Future<bool> Function() repair,
  }) async {
    final prefs = await AppState.prefs;
    final repairedIds = prefs.getStringList(_unlockedRepairPreferenceKey) ?? [];
    final id = noteId.toString();

    if (repairedIds.contains(id) && await previewIsComplete()) return true;
    if (!await repair() || !await previewIsComplete()) return false;

    if (!repairedIds.contains(id)) {
      await prefs.setStringList(_unlockedRepairPreferenceKey, [
        ...repairedIds,
        id,
      ]);
    }
    return true;
  }

  /// Repairs local-only attachment presentation fields after the PIN flow has
  /// decrypted the files. Both operations always run so one attachment type
  /// cannot prevent another from self-healing.
  @visibleForTesting
  static Future<SketchPreviewRepairBatchResult> repairDecryptedAttachments(
    Note note, {
    Set<String> completedSketchKeys = const {},
    Future<Uint8List> Function(String path)? readBytes,
    Future<void> Function(String path, Uint8List bytes)? writeBytes,
    Future<bool> Function(Note note)? repairThumbnails,
    Future<SketchPreviewRepairBatchResult> Function(Note note)? repairSketches,
  }) async {
    final thumbnailsChanged =
        await (repairThumbnails ??
            (target) => target.generateMissingAttachmentThumbnails(
              readBytes: readBytes,
            ))(note);
    final sketches =
        await (repairSketches ??
            (target) => repairNote(
              target,
              scope: SketchPreviewRepairScope.allSketches,
              reuseExistingPreviews: false,
              updateCache: false,
              completedSketchKeys: completedSketchKeys,
              generatePreview:
                  previewGeneratorOverride ??
                  (sketch) => SketchPreviewGenerator.generatePreview(
                    sketch,
                    reuseExistingPreview: false,
                    updateCache: false,
                    readBytes: readBytes,
                    writeBytes: writeBytes,
                  ),
            ))(note);
    return SketchPreviewRepairBatchResult(
      changed: thumbnailsChanged || sketches.changed,
      hasRetryableFailure: sketches.hasRetryableFailure,
      completedSketchKeys: sketches.completedSketchKeys,
      failedSketchKeys: sketches.failedSketchKeys,
      discardedPreviewPaths: sketches.discardedPreviewPaths,
    );
  }

  @visibleForTesting
  static Future<bool> hasCompleteLocalAttachmentPreviews(
    Note note, {
    Future<bool> Function(String path)? pathExists,
  }) async {
    for (final image in note.images) {
      if (image.blurredThumbnail == null || image.blurredThumbnail!.isEmpty) {
        return false;
      }
    }

    final fs = await fileSystem();
    final exists = pathExists ?? fs.exists;
    for (final sketch in note.sketches) {
      // A protected, corrupt, missing, or quarantined source must not be
      // recorded as repaired merely because its in-memory stroke list is empty.
      if (sketch.requiresLegacyMigration || !sketch.hasHydratedStrokeSource) {
        return false;
      }
      if (sketch.strokes.isEmpty) continue;
      if (!await _hasUsableLocalPreview(sketch, exists)) return false;
    }
    return true;
  }

  static void _copyPreviewFields(Note source, Note target) {
    for (final targetImage in target.images) {
      final matches = source.images.where(
        (candidate) => candidate.src == targetImage.src,
      );
      final sourceImage = matches.isEmpty ? null : matches.first;
      if (sourceImage == null) continue;
      targetImage.blurredThumbnail = sourceImage.blurredThumbnail;
    }

    for (final targetSketch in target.sketches) {
      final matches = source.sketches.where(
        (candidate) =>
            candidate.strokesFilePath == targetSketch.strokesFilePath,
      );
      final sourceSketch = matches.isEmpty ? null : matches.first;
      if (sourceSketch == null) continue;

      targetSketch.previewImage = sourceSketch.previewImage;
      targetSketch.blurredThumbnail = sourceSketch.blurredThumbnail;
      targetSketch.aspectRatio = sourceSketch.aspectRatio;
      targetSketch.strokes = sourceSketch.strokes;
      targetSketch.backgroundColor = sourceSketch.backgroundColor;
      targetSketch.pagePattern = sourceSketch.pagePattern;
      if (sourceSketch.hasHydratedStrokeSource) {
        targetSketch.markStrokesHydrated();
      }
    }
  }

  @visibleForTesting
  static String sourceSignatureFor(Note note) {
    final sources = <Map<String, Object?>>[
      for (final (index, sketch) in note.sketches.indexed)
        {
          'index': index,
          'strokesFilePath': sketch.strokesFilePath,
          'strokesContentHash': sketch.strokesContentHash,
          'backgroundImage': sketch.backgroundImage,
        },
    ];
    return sha256.convert(utf8.encode(jsonEncode(sources))).toString();
  }

  static String _sketchSourceKey(int index, SketchData sketch) {
    return sha256
        .convert(
          utf8.encode(
            jsonEncode({
              'index': index,
              'strokesFilePath': sketch.strokesFilePath,
              'strokesContentHash': sketch.strokesContentHash,
              'backgroundImage': sketch.backgroundImage,
            }),
          ),
        )
        .toString();
  }

  static Future<bool> _hasUsableLocalPreview(
    SketchData sketch,
    Future<bool> Function(String path) pathExists,
  ) async {
    final previewPath = sketch.previewImage;
    return previewPath != null &&
        previewPath.isNotEmpty &&
        !previewPath.startsWith('http') &&
        sketch.blurredThumbnail != null &&
        sketch.blurredThumbnail!.isNotEmpty &&
        await pathExists(previewPath);
  }

  static Map<int, SketchPreviewLocalProgress> _loadProgress(
    SharedPreferences prefs,
  ) {
    final raw = prefs.getString(_progressPreferenceKey);
    if (raw == null || raw.isEmpty) return {};
    try {
      final decoded = jsonDecode(raw);
      if (decoded is! Map<String, dynamic>) return {};
      return {
        for (final entry in decoded.entries)
          if (int.tryParse(entry.key) case final id? when entry.value is Map)
            id: SketchPreviewLocalProgress.fromJson(
              Map<String, dynamic>.from(entry.value as Map),
            ),
      };
    } catch (_) {
      return {};
    }
  }

  static Future<void> _saveProgress(
    SharedPreferences prefs,
    Map<int, SketchPreviewLocalProgress> progress,
  ) async {
    final encoded = <String, dynamic>{
      for (final entry in progress.entries)
        entry.key.toString(): entry.value.toJson(),
    };
    await prefs.setString(_progressPreferenceKey, jsonEncode(encoded));
  }

  static Future<void> _recordForcedRepairOutcome(
    int noteId,
    SketchPreviewRepairResult result,
  ) async {
    if (!result.isComplete || result.sourceSignature.isEmpty) return;
    final prefs = await AppState.prefs;
    final progress = _loadProgress(prefs);
    progress[noteId] = advanceLocalProgress(
      previous: progress[noteId],
      result: result,
    );
    await _saveProgress(prefs, progress);
  }

